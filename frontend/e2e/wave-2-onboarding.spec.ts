import { expect, test, type Page } from '@playwright/test'
import { mkdir } from 'node:fs/promises'
import path from 'node:path'
import { execFileSync } from 'node:child_process'

// Dedicated config starts a real API against fresh temporary SQLite. No API mocks or seeds.
test.describe.configure({ mode: 'serial' })
const longName = 'Prusament Galaxy Black — Spool principal para peças grandes e protótipos'

async function layout(page: Page, name: string) {
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), name + ': overflow').toBe(true)
  await page.screenshot({ path: test.info().outputPath(name + '.png'), fullPage: true })
}
async function documentationShot(page: Page, name: string) {
  if (process.env.FCC_WAVE2_SCREENSHOTS !== '1') return
  const directory = path.resolve('../docs/user-guide/images/wave2')
  await mkdir(directory, { recursive: true })
  await page.screenshot({ path: path.join(directory, name + '.png'), fullPage: true })
}
async function newSpool(page: Page, name: string) {
  await page.goto('/inventory/new')
  await page.locator('#spool-manufacturerId').selectOption({ label: 'Prusament' })
  await page.locator('#spool-materialId').selectOption({ label: 'PLA' })
  await page.locator('#spool-colorName').fill('Galaxy Black')
  await page.locator('#spool-displayName').fill(name)
  await page.locator('#spool-purchasePrice').fill('25')
  await page.getByRole('button', { name: 'Create Spool', exact: true }).click()
  await expect(page).toHaveURL(/\/inventory$/)
  await expect(page.getByText(name, { exact: true })).toBeVisible()
}

test('browser-only onboarding, catalog CRUD, protected deletion and locale persistence', async ({ page }) => {
  test.setTimeout(600_000)
  const doctor = execFileSync(process.execPath, ['scripts/browser-doctor.mjs'], {
    encoding: 'utf8', env: { ...process.env, FCC_DOCTOR_FRONTEND_URL: 'http://127.0.0.1:15173/', FCC_DOCTOR_BACKEND_URL: 'http://127.0.0.1:18002/api/health' },
  })
  await test.info().attach('browser-doctor', { body: doctor, contentType: 'text/plain' })
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Seu inventário de filamentos está vazio.' })).toBeVisible()
  await documentationShot(page, 'empty-inventory-desktop')
  await page.goto('/settings')
  await page.getByRole('combobox', { name: 'Idioma', exact: true }).selectOption('en')
  await page.getByRole('link', { name: /Catalogs/ }).click()
  await expect(page.getByText('No manufacturers yet.')).toBeVisible()
  await page.goto('/inventory/new')
  await expect(page.getByRole('button', { name: 'Create Spool' })).toBeDisabled()
  await page.getByRole('link', { name: 'Open Catalogs' }).click()
  await expect(page.getByText('No materials yet.')).toBeVisible()
  await page.getByRole('button', { name: 'Add manufacturer', exact: true }).first().click()
  await page.getByRole('textbox', { name: 'Name', exact: true }).fill('Prusament')
  await page.getByRole('button', { name: 'Save', exact: true }).click()
  await expect(page.getByText('Prusament', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Add material', exact: true }).first().click()
  await page.getByRole('textbox', { name: 'Name', exact: true }).fill('PLA')
  await page.getByRole('textbox', { name: 'Category', exact: true }).fill('PLA')
  await page.getByRole('spinbutton', { name: /Density/ }).fill('1.24')
  await page.getByRole('button', { name: 'Save', exact: true }).click()
  await expect(page.getByText('PLA', { exact: true }).first()).toBeVisible()
  for (const sectionName of ['Manufacturers', 'Materials']) {
    const section = page.locator('section').filter({ has: page.getByRole('heading', { name: sectionName, exact: true }) }).last()
    await section.getByRole('button', { name: 'Edit', exact: true }).click()
    if (sectionName === 'Manufacturers') await section.getByRole('textbox', { name: /Website/ }).fill('https://example.com')
    else await section.getByRole('textbox', { name: /Notes/ }).fill('Density confirmed from technical sheet')
    await section.getByRole('button', { name: 'Save', exact: true }).click()
    await expect(section.locator('form')).toHaveCount(0)
  }
  await newSpool(page, longName)
  await page.reload()
  await expect(page.getByText(longName, { exact: true })).toBeVisible()
  await newSpool(page, 'Segundo Spool')
  await page.goto('/settings/catalogs')
  page.on('dialog', dialog => dialog.accept())
  for (const sectionName of ['Manufacturers', 'Materials']) {
    const section = page.locator('section').filter({ has: page.getByRole('heading', { name: sectionName, exact: true }) }).last()
    await section.getByRole('button', { name: 'Delete', exact: true }).click()
    await expect(section.getByRole('alert')).toContainText('cannot be deleted')
  }
  for (const kind of ['manufacturer', 'material']) {
    await page.getByRole('button', { name: 'Add ' + kind, exact: true }).first().click()
    await page.getByRole('textbox', { name: 'Name', exact: true }).fill('Unused ' + kind)
    if (kind === 'material') await page.getByRole('textbox', { name: 'Category', exact: true }).fill('PLA')
    await page.getByRole('button', { name: 'Save', exact: true }).click()
    const row = page.getByRole('listitem').filter({ hasText: 'Unused ' + kind })
    await row.getByRole('button', { name: 'Delete', exact: true }).click()
    await expect(row).toHaveCount(0)
  }
  await page.goto('/settings')
  await page.getByRole('combobox', { name: 'Language', exact: true }).selectOption('pt-BR')
  await page.reload()
  await expect(page.getByRole('combobox', { name: 'Idioma', exact: true })).toHaveValue('pt-BR')
  await page.goto('/settings/catalogs')
  await expect(page.getByRole('heading', { name: 'Catálogos', level: 2, exact: true })).toBeVisible()
  await expect(page.getByText('Prusament', { exact: true })).toBeVisible()
  await documentationShot(page, 'catalogs-desktop')
  await expect(page.locator('nav').getByRole('link', { name: /Analytics|Análises/ })).toHaveCount(0)
})

for (const width of [390, 320]) {
  test(width + 'x844 real mobile flows, multi-Spool cost, Finish, QR and G-code', async ({ page }) => {
    test.setTimeout(600_000)
    await page.setViewportSize({ width, height: 844 })
    await page.goto('/')
    await expect(page.getByRole('list', { name: 'Spools na visualização em grade' })).toBeVisible()
    await layout(page, 'inventory')
    await page.goto('/settings/catalogs')
    await page.getByRole('button', { name: 'Adicionar material', exact: true }).click()
    await expect(page.getByRole('textbox', { name: 'Nome', exact: true })).toBeVisible()
    await layout(page, 'catalogs-form')
    await page.getByRole('button', { name: 'Cancelar', exact: true }).click()
    if (width === 390) await documentationShot(page, 'catalogs-mobile')
    await page.goto('/inventory/new')
    await page.locator('#spool-displayName').fill(longName)
    await layout(page, 'new-spool')
    const createSpool = page.getByRole('button', { name: 'Criar Spool', exact: true })
    await createSpool.scrollIntoViewIfNeeded()
    await expect(createSpool).toBeInViewport()
    await page.goto('/spools/FIL-0001')
    await expect(page.locator('#spool-details-title')).toBeVisible()
    await layout(page, 'spool-details')
    await page.goto('/prints/new')
    await page.getByLabel('Nome da Impressão', { exact: true }).fill('Mobile ' + width + ' — impressão com dois Spools')
    await page.getByLabel('Spool', { exact: true }).first().selectOption('1')
    await page.getByLabel('Peso Estimado', { exact: true }).first().fill('10')
    await page.getByRole('button', { name: 'Adicionar Spool' }).click()
    await page.getByLabel('Spool', { exact: true }).nth(1).selectOption('2')
    await page.getByLabel('Peso Estimado', { exact: true }).nth(1).fill('20')
    await expect(page.getByTestId('estimated-print-cost-EUR')).toContainText('0,75')
    await layout(page, 'new-print')
    await page.getByRole('button', { name: 'Criar Impressão', exact: true }).click()
    await expect(page).toHaveURL(/\/prints$/)
    const card = page.locator('article').filter({ hasText: 'Mobile ' + width + ' — impressão com dois Spools' })
    await card.getByRole('button', { name: 'Iniciar Impressão' }).click()
    await page.getByRole('dialog').getByRole('button', { name: 'Iniciar Impressão' }).click()
    await expect(page.getByRole('dialog')).toHaveCount(0)
    await card.getByRole('button', { name: 'Finalizar Impressão' }).click()
    const dialog = page.getByRole('dialog')
    await dialog.locator('input[data-spool-id]').nth(0).fill('10')
    await dialog.locator('input[data-spool-id]').nth(1).fill('20')
    await layout(page, 'finish-print')
    const bounds = await dialog.boundingBox()
    expect(bounds!.x).toBeGreaterThanOrEqual(0)
    expect(bounds!.x + bounds!.width).toBeLessThanOrEqual(width)
    expect(bounds!.y + bounds!.height).toBeLessThanOrEqual(844)
    await expect(dialog.getByRole('button', { name: 'Finalizar Impressão' })).toBeInViewport()
    await dialog.getByRole('button', { name: 'Finalizar Impressão' }).click()
    await expect(dialog).toHaveCount(0)
    if (width === 320) return
    await page.goto('/scan')
    await page.getByLabel('Código do Spool', { exact: true }).fill('FIL-0001')
    await layout(page, 'qr-scanner')
    await page.getByRole('button', { name: 'Abrir Spool' }).click()
    await expect(page).toHaveURL(/\/qr\/spool\/FIL-0001$/)
    await page.goto('/gcode')
    await page.locator('input[type=file]').setInputFiles({ name: 'wave2.gcode', mimeType: 'text/plain', buffer: Buffer.from('; filament_type = PLA\n; TIME:120\nG21\nG90\nM82\nM104 S210\nG1 X0 Y0 Z0.2 F1200\nG1 X20 Y20 E10 F1200\n') })
    await page.getByRole('button', { name: 'Enviar G-code' }).click()
    await page.getByRole('button', { name: 'Analisar G-code', exact: true }).click()
    await expect(page.getByRole('heading', { name: 'Arquivo analisado' })).toBeVisible()
    await page.getByRole('button', { name: 'Calcular peso' }).click()
    await expect(page.getByRole('region', { name: 'Resultado do peso estimado' })).toBeVisible()
    await layout(page, 'gcode')
    await page.goto('/settings')
    await expect(page.getByRole('link', { name: 'Baixar manual (PDF)' })).toBeVisible()
    await layout(page, 'settings')
  })
}
