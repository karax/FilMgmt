UPLOAD_ID = UUID("93e88bde-fcb5-4929-b4a2-50c3d9f201cc")


def parse(lines):
    return GenericGCodeParser().parse_lines(
        lines,
        upload_id=UPLOAD_ID,
        filename="fixture.gcode",
    )


def tool(result, number: int):
    return next(item for item in result.tools if item.tool == number)


def store_upload(tmp_path: Path, contents: bytes):
    service = GCodeUploadService(
        storage_directory=tmp_path / "uploads",
        max_upload_bytes=max(len(contents), 1) + 100,
        chunk_size=7,
    )
    metadata = asyncio.run(
        service.persist_upload(
            UploadFile(file=BytesIO(contents), filename="fixture.gcode"),
        ),
    )
    return service, metadata, service.resolve_upload(metadata.upload_id).path


def test_line_parser_extracts_command_parameters_and_comment() -> None:
    parsed = parse_gcode_line("G1 X10 Y20 E0.5 ; move")

    assert parsed.command == "G1"
    assert parsed.parameters == {"X": 10.0, "Y": 20.0, "E": 0.5}
    assert parsed.comment == "move"
    assert parsed.malformed is False


def test_line_parser_supports_parameters_without_spaces() -> None:
    parsed = parse_gcode_line("G1X10Y20E0.5")

    assert parsed.command == "G1"
    assert parsed.parameters == {"X": 10.0, "Y": 20.0, "E": 0.5}


def test_no_space_integer_e_parameter_is_not_treated_as_an_exponent() -> None:
    parsed = parse_gcode_line("G1X10E3")

    assert parsed.parameters == {"X": 10.0, "E": 3.0}


def test_line_parser_normalizes_case_and_numeric_command_padding() -> None:
    parsed = parse_gcode_line("  g01 x10 y-2.3 e+1e-3")

    assert parsed.command == "G1"
    assert parsed.parameters == {"X": 10.0, "Y": -2.3, "E": 0.001}


def test_line_parser_ignores_line_number_and_checksum() -> None:
    parsed = parse_gcode_line("N123 G1 X10*42")

    assert parsed.command == "G1"
    assert parsed.parameters == {"X": 10.0}
