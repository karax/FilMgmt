def test_first_parse_writes_small_atomic_cache_and_second_reuses_it(tmp_path: Path) -> None:
    contents = b"M83\nG1 E5\n"
    upload_service, metadata, upload_path = store_upload(tmp_path, contents)
    parser = CountingParser()
    service = GCodeParseService(upload_service=upload_service, parser=parser)

    first = service.parse_upload(metadata.upload_id)
    second = service.parse_upload(metadata.upload_id)

    cache_path = service.cache_path_for(upload_path)
    assert first == second
    assert parser.calls == 1
    assert cache_path.is_file()
    assert cache_path.stat().st_size < 20_000
    assert not cache_path.with_suffix(".json.uploading").exists()
    assert json.loads(cache_path.read_text())["parser_version"] == PARSER_VERSION
    assert upload_path.read_bytes() == contents


def test_incompatible_parser_version_forces_reparse(tmp_path: Path) -> None:
    upload_service, metadata, upload_path = store_upload(tmp_path, b"G1 X1\n")
    parser = CountingParser()
    service = GCodeParseService(upload_service=upload_service, parser=parser)
    cache_path = service.cache_path_for(upload_path)
    cache_path.write_text('{"parser_version": 0}', encoding="utf-8")

    result = service.parse_upload(metadata.upload_id)

    assert result.parser_version == PARSER_VERSION
    assert parser.calls == 1
    assert json.loads(cache_path.read_text())["parser_version"] == PARSER_VERSION


class SinglePassLines:
    def __init__(self, count: int) -> None:
        self.count = count
        self.iteration_count = 0

    def __iter__(self):
        self.iteration_count += 1
        if self.iteration_count > 1:
            raise AssertionError("line iterable was consumed more than once")
        for _ in range(self.count):
            yield "G1 X1\n"


class CountingParser(GenericGCodeParser):
    def __init__(self) -> None:
        self.calls = 0

    def parse_path(self, *args, **kwargs):
        self.calls += 1
        return super().parse_path(*args, **kwargs)
