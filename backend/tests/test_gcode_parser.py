def test_line_parser_supports_parenthesis_and_comment_only_lines() -> None:
    inline = parse_gcode_line("G1 X2 (move axis)")
    comment = parse_gcode_line("; generated by = Unit Test")

    assert inline.comment == "move axis"
    assert inline.parameters == {"X": 2.0}
    assert comment.command is None
    assert comment.comment == "generated by = Unit Test"


